// Loader for the phase-00b golden fixtures under `src/test/resources/parity`, generated by
// `scripts/emit_parity_fixtures.py` from the real Python `MoveTracker`.
//
// Read `parity/README.md` for the schema and the regeneration command. Everything here is
// read-only: the fixtures are ground truth, so a mismatch is a port bug or a `STATUS.md`
// discrepancy — never loosen a tolerance to get a test green.
//
// ---------------------------------------------------------------------------------------
// Tolerance contract (binding for every later phase)
// ---------------------------------------------------------------------------------------

/** Relative tolerance for every fixture float. */
const val PARITY_REL_TOL: Double = 1e-4

/** Absolute floor, so near-zero values do not require exact bits. */
const val PARITY_ABS_FLOOR: Double = 1e-4

/** `|e - a| <= 1e-4 * max(1.0, |e|)`: relative, with a 1e-4 absolute floor. */
fun parityClose(
    expected: Double,
    actual: Double,
): Boolean = abs(expected - actual) <= PARITY_REL_TOL * maxOf(1.0, abs(expected))

fun assertClose(
    expected: Double,
    actual: Double,
    what: String,
) {
    if (!parityClose(expected, actual)) {
        fail<Unit>(
            "$what: expected $expected, got $actual " +
                "(tolerance $PARITY_REL_TOL relative, absolute floor $PARITY_ABS_FLOOR)",
        )
    }
}

fun assertCloseMap(
    expected: Map<String, Double>,
    actual: Map<String, Double>,
    what: String,
) {
    assertEquals(expected.keys.sorted(), actual.keys.sorted(), "$what: key sets differ")
    for (key in expected.keys.sorted()) {
        assertClose(expected.getValue(key), actual.getValue(key), "$what[$key]")
    }
}

/** Sets, decisions, counts and strings are compared EXACTLY — never with a tolerance. */
fun assertExact(
    expected: Set<String>,
    actual: Set<String>,
    what: String,
) {
    assertEquals(expected.sorted(), actual.sorted(), what)
}

fun assertExactList(
    expected: List<String>,
    actual: List<String>,
    what: String,
) {
    assertEquals(expected, actual, what)
}

fun assertConsumed(
    values: Collection<*>,
    what: String,
) {
    assertTrue(values.isNotEmpty(), "$what must not be empty — the fixture was never consumed")
}

