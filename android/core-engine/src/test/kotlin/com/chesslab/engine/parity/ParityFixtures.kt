/**
 * One clip's fixture.
 *
 * Planes are delta-encoded against the previous *emitted* frame (`meta.planeEncoding ==
 * "delta-u8"`), so decoding walks the chain from the start; the walk is cached, which makes
 * iterating [frames] in ascending order O(n).
 */
class ParityClip internal constructor(
    val name: String,
    val meta: ParityMeta,
    val frames: List<ParityFrame>,
) {
    private val grayChain =
        PlaneChain(meta.frames, meta.detSize * meta.detSize) { idx ->
            ParityFixtures.resourceBytes("/parity/$name/planes/${pad(idx)}.gray.bin.gz")
        }

    private val bgrChain =
        PlaneChain(meta.framesWithBgr, meta.detSize * meta.detSize * meta.channelsBgr) { idx ->
            ParityFixtures.resourceBytes("/parity/$name/planes/${pad(idx)}.bgr.bin.gz")
        }

    fun gray(frame: Int): GrayImage = GrayImage(meta.detSize, meta.detSize, grayChain.plane(frame))

    fun bgr(frame: Int): BgrImage? =
        if (frame !in meta.framesWithBgr) {
            null
        } else {
            BgrImage(meta.detSize, meta.detSize, bgrChain.plane(frame))
        }

    fun frame(index: Int): ParityFrame = frames.first { it.frame == index }

    /** Frames carrying a full Tier-A record (the tracker computed detection evidence there). */
    fun tierAFrames(): List<ParityFrame> = frames.filter { it.tierA != null }

    private fun pad(idx: Int): String = idx.toString().padStart(PAD_WIDTH, '0')

    internal companion object {
        const val PAD_WIDTH = 4
    }
}

private class PlaneChain(
    private val order: List<Int>,
    private val size: Int,
    private val load: (Int) -> ByteArray,
) {
    private var cursor = -1
    private var buffer = ByteArray(size)

    fun plane(frame: Int): ByteArray {
        val target = order.indexOf(frame)
        require(target >= 0) { "frame $frame is not part of this plane stream" }
        if (target < cursor) {
            cursor = -1
            buffer = ByteArray(size)
        }
        while (cursor < target) {
            cursor += 1
            applyDelta(load(order[cursor]))
        }
        return buffer.copyOf()
    }

    private fun applyDelta(deltaGz: ByteArray) {
        val delta = ParityFixtures.gunzip(deltaGz)
        require(delta.size == size) { "plane size ${delta.size} != expected $size" }
        for (i in 0 until size) {
            buffer[i] = (buffer[i] + delta[i]).toByte()
        }
    }
}

object ParityFixtures {
    private val json = Json { ignoreUnknownKeys = true }
    private val cache = mutableMapOf<String, ParityClip>()

    fun index(): ParityIndex = json.decodeFromString(resourceText("/parity/index.json"))

    fun clips(): List<String> = index().clips

    fun load(name: String): ParityClip =
        cache.getOrPut(name) {
            val meta: ParityMeta = json.decodeFromString(resourceText("/parity/$name/meta.json"))
            val frames =
                meta.frames.map { idx ->
                    val padded = idx.toString().padStart(ParityClip.PAD_WIDTH, '0')
                    json.decodeFromString<ParityFrame>(resourceText("/parity/$name/frames/$padded.json"))
                }
            ParityClip(name, meta, frames)
        }

    /** Shared BGR->HSV/Lab conversion fixture, `patch` in `sweep|board`, `space` in `bgr|hsv|lab`. */
    fun colorSpacePlane(
        patch: String,
        space: String,
    ): ByteArray = gunzip(resourceBytes("/parity/_colorspace/planes/$patch.$space.bin.gz"))

    fun colorSpaceMeta(): String = resourceText("/parity/_colorspace/meta.json")

    /** Shared, image-free geometry fixture (square regions, crop boxes, homographies). */
    fun geometryMeta(): String = resourceText("/parity/_geometry/meta.json")

    /**
     * Reads a JSON-lines fixture, e.g. `_cnn/cnn_observation.jsonl`,
     * `_geometry/resolve_corners.jsonl`, `_geometry/grid_coverage.jsonl`.
     */
    fun jsonl(path: String): List<JsonObject> =
        resourceText("/parity/$path")
            .lineSequence()
            .filter { it.isNotBlank() }
            .map { json.parseToJsonElement(it).jsonObject }
            .toList()

    /** Raw gzipped gray plane referenced by `_geometry/grid_coverage.jsonl`. */
    fun geometryPlane(relative: String): ByteArray = gunzip(resourceBytes("/parity/_geometry/$relative"))

    internal fun resourceBytes(path: String): ByteArray =
        requireNotNull(ParityFixtures::class.java.getResourceAsStream(path)) {
            "missing fixture resource $path — re-run scripts/emit_parity_fixtures.py"
        }.use { it.readBytes() }

    internal fun resourceText(path: String): String = resourceBytes(path).toString(Charsets.UTF_8)

    internal fun gunzip(bytes: ByteArray): ByteArray {
        val out = ByteArrayOutputStream(bytes.size * GUNZIP_GUESS)
        GZIPInputStream(bytes.inputStream()).use { it.copyTo(out) }
        return out.toByteArray()
    }

    private const val GUNZIP_GUESS = 4
}
