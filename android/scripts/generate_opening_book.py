"""Build the compact Android opening book from lichess-org/chess-openings TSV files.

The generated assets contain facts, not python-chess objects: named positions and the
known continuations that reach them.  Keeping generation outside the app makes loading
the book cheap and keeps the exact upstream revision reproducible.
"""

from __future__ import annotations

import argparse
import collections
import csv
import io
from pathlib import Path

import chess
import chess.pgn


def position_key(board: chess.Board) -> str:
    """Opening identity; clocks and transient en-passant state do not name an opening."""
    return " ".join(board.fen(en_passant="legal").split()[:3])


def moves_of(pgn: str) -> list[chess.Move]:
    game = chess.pgn.read_game(io.StringIO(pgn))
    if game is None or game.errors:
        raise ValueError(f"Cannot parse opening line: {pgn!r}")
    return list(game.mainline_moves())


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", type=Path, action="append", required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--revision", required=True)
    args = parser.parse_args()

    named: dict[str, tuple[str, str, int]] = {}
    continuations: collections.Counter[tuple[str, str]] = collections.Counter()

    for source in args.input:
        with source.open(encoding="utf-8", newline="") as handle:
            for row in csv.DictReader(handle, delimiter="\t"):
                moves = moves_of(row["pgn"])
                board = chess.Board()
                for move in moves:
                    continuations[position_key(board), move.uci()] += 1
                    board.push(move)
                key = position_key(board)
                candidate = (row["eco"], row["name"], len(moves))
                # A transposition can have several labels. Prefer the most specific/deepest
                # canonical line, then use the stable name as the tie breaker.
                previous = named.get(key)
                if previous is None or (candidate[2], candidate[1]) > (previous[2], previous[1]):
                    named[key] = candidate

    output = args.output
    output.mkdir(parents=True, exist_ok=True)
    with (output / "openings.tsv").open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle, delimiter="\t", lineterminator="\n")
        writer.writerow(("position", "eco", "name", "canonicalPlies"))
        for key, (eco, name, plies) in sorted(named.items()):
            writer.writerow((key, eco, name, plies))

    with (output / "continuations.tsv").open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle, delimiter="\t", lineterminator="\n")
        writer.writerow(("position", "uci", "references"))
        for (key, uci), references in sorted(continuations.items()):
            writer.writerow((key, uci, references))

    (output / "NOTICE.txt").write_text(
        "Chess opening names and lines\n"
        "Source: https://github.com/lichess-org/chess-openings\n"
        f"Revision: {args.revision}\n"
        "License: CC0 1.0 Universal / public domain\n"
        "Generated by android/scripts/generate_opening_book.py.\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
